"use client";

import { useCallback, useEffect, useRef } from "react";
import { apiFetch } from "@/lib/api";

// Gap of silence after one spoken line fully finishes before the next one
// starts — back-to-back speech with no gap is hard for a kindergartner to
// follow.
const POST_SPEECH_PAUSE_MS = 500;

// Safety ceiling for one clip. Covers cases the fetch .catch/audio.onerror
// paths below don't: a play() promise or 'ended' event that never settles
// (seen in some embedded/kiosk WebViews with blocked autoplay). Without this,
// finish() never runs and games that advance from onEnd (LongOrShort,
// NumberRecognition, SameOrDifferent, NumberColoring) softlock on that round
// forever. Generous because it must never cut off audio that's genuinely
// still playing normally.
const SPEECH_WATCHDOG_MS = 12000;

// Matches the 2s revealZoom keyframes in the games' CSS, so the next question never cuts the correct-answer zoom short.
export const REVEAL_MIN_MS = 2000;

// Once a clip is really playing, the stall watchdog is replaced by this far longer one, so a long sentence is never cut off mid-speech.
const PLAYING_WATCHDOG_MS = 90000;

/**
 * Text-to-speech for learner-facing games. Speech is generated by
 * ElevenLabs through our own /api/tts proxy (the API key stays server-side)
 * and cached there, so repeat lines are near-instant.
 */
export function useSpeech() {
  const audioRef = useRef<HTMLAudioElement | null>(null);
  // True from the moment a line starts (its /api/tts fetch is issued) until
  // it actually ends — unlike checking audioRef, this covers the in-flight
  // fetch window too, before an Audio element even exists.
  const busyRef = useRef(false);
  const queueRef = useRef<Array<() => void>>([]);
  // Bumped on every start() and every interrupt/stop, so a fetch response
  // that arrives after its line was superseded knows to drop itself instead
  // of creating and playing an Audio element nobody asked for anymore.
  const tokenRef = useRef(0);
  // Tracks whether this component instance is actually mounted, surviving
  // React StrictMode's dev-only mount -> cleanup -> mount cycle: the
  // cleanup pass sets this false, the second setup pass sets it back true
  // before any deferred callback below runs, so a genuine unmount (this
  // flag left false) is the only case that cancels a pending speakAll().
  const mountedRef = useRef(true);
  useEffect(() => {
    mountedRef.current = true;
    return () => {
      mountedRef.current = false;
    };
  }, []);

  const runNext = useCallback(() => {
    queueRef.current.shift()?.();
  }, []);

  const speak = useCallback(
    (text: string, onEnd?: () => void, opts?: { interrupt?: boolean; pauseMs?: number; minMs?: number; onStart?: () => void }) => {
      const start = () => {
        const myToken = ++tokenRef.current;
        const startedAt = Date.now();
        busyRef.current = true;

        // One line ends once. A clip that 404s or won't decode fires the
        // element's error event *and* rejects play(), and both are wired to
        // finish() below — without this flag that schedules two pauses, so
        // onEnd runs twice and the queue is shifted twice. In the games that
        // advance from onEnd (LongOrShort, NumberRecognition,
        // SameOrDifferent, NumberColoring) a single failed clip would
        // skip a whole round.
        let ended = false;

        // onStart lets a game show something the moment its words are heard; a clip that never plays still calls it, so nothing stays hidden.
        let started = false;
        const markStarted = () => {
          if (started || tokenRef.current !== myToken) return;
          started = true;
          opts?.onStart?.();
        };

        let watchdog = window.setTimeout(() => finish(), SPEECH_WATCHDOG_MS);

        const finish = () => {
          if (ended || tokenRef.current !== myToken) return;
          markStarted();
          ended = true;
          window.clearTimeout(watchdog);
          // busy stays true across the pause. Clearing it here instead would
          // make every inter-line gap look idle, so a feedback line sent with
          // interrupt: false would take the interrupt path below and wipe the
          // queue — dropping lines that were legitimately waiting, including
          // the ones games advance the round from.
          // pauseMs shortens the gap for lines that belong together, like counting one number per line.
          // minMs holds onEnd until an on-screen animation (the wrong-answer reveal) has fully played, even when the clip fails fast.
          const pause = Math.max(opts?.pauseMs ?? POST_SPEECH_PAUSE_MS, (opts?.minMs ?? 0) - (Date.now() - startedAt));
          window.setTimeout(() => {
            // Re-checked, not just checked in finish(): stop() or a newer
            // line during the pause must cancel this onEnd too. Without it a
            // superseded line still fires its onEnd into whatever is playing
            // now, cutting that line off and stranding *its* onEnd.
            if (tokenRef.current !== myToken) return;
            busyRef.current = false;
            onEnd?.();
            runNext();
          }, pause);
        };

        apiFetch("/api/tts", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ text }),
        })
          .then((res) => {
            if (!res.ok) throw new Error("tts request failed");
            return res.json() as Promise<{ url: string }>;
          })
          .then(({ url }) => {
            // Superseded while the fetch was in flight — a newer speak()
            // already owns playback, so this response must never play.
            // A clip that arrives after the watchdog already moved on would play over the next line, so it is dropped too.
            if (ended || tokenRef.current !== myToken) return;
            const audio = new Audio(url);
            audioRef.current = audio;
            audio.onended = finish;
            audio.onerror = finish;
            // The short watchdog only guards a clip that never starts; one that is playing may run as long as it needs.
            audio.onplaying = () => {
              markStarted();
              window.clearTimeout(watchdog);
              watchdog = window.setTimeout(() => finish(), PLAYING_WATCHDOG_MS);
            };
            return audio.play();
          })
          .catch(() => {
            // Speech failing (offline, API down, autoplay blocked) must not
            // softlock the game — a replay button lets the child retry, and
            // the game still advances on its own.
            finish();
          });
      };

      // interrupt: false (used for correct/wrong feedback lines) queues
      // behind whatever's currently speaking or still being fetched, so it
      // starts only once that line fully finishes — never racing it. The
      // queue length matters as well as busy: a non-interrupting line must
      // never reach the fallthrough below while other lines are still
      // waiting, or it would clear them and jump the order.
      if (
        opts?.interrupt === false &&
        (busyRef.current || queueRef.current.length > 0)
      ) {
        queueRef.current.push(start);
        return;
      }

      queueRef.current = [];
      audioRef.current?.pause();
      busyRef.current = false;
      start();
    },
    [runNext],
  );

  /**
   * Speaks several lines back to back as one unit, with the usual pause
   * between them, running `onEnd` after the last one. Every line after the
   * first is queued (interrupt: false) rather than chained through nested
   * onEnd callbacks, so a line's clip is already being fetched while the
   * one before it is still playing.
   *
   * Deferred a tick so it runs after StrictMode's phantom cleanup -> remount
   * has settled: calling speak() synchronously from a game's very first
   * mount effect (any game whose intro doesn't wait on a data fetch first —
   * Similarities and Shape both build/derive their content synchronously)
   * races that phantom cleanup, which bumps the token above and silently
   * drops the intro's response as "superseded" before it ever plays. If the
   * component is genuinely gone by the time the timer fires (mountedRef
   * false), it's skipped instead of speaking into an unmounted screen.
   */
  const speakAll = useCallback(
    (lines: string[], onEnd?: () => void) => {
      window.setTimeout(() => {
        if (!mountedRef.current) return;
        lines.forEach((line, i) => {
          const isLast = i === lines.length - 1;
          speak(line, isLast ? onEnd : undefined, i === 0 ? undefined : { interrupt: false });
        });
      }, 0);
    },
    [speak],
  );

  const stop = useCallback(() => {
    queueRef.current = [];
    tokenRef.current++;
    busyRef.current = false;
    audioRef.current?.pause();
  }, []);

  return { speak, speakAll, stop };
}

// The picker page (/learner) caches the chosen child here as {firstName, ...}
// — see that page's handleSelectLearner. Read directly (rather than through
// React state) so a one-time intro greeting can use the name on its very
// first speak() call without a re-render race.
export function getLearnerFirstName(): string | null {
  try {
    const saved = sessionStorage.getItem("selectedLearner");
    if (!saved) return null;
    const learner = JSON.parse(saved) as { firstName?: string };
    return learner.firstName ?? null;
  } catch {
    return null;
  }
}

// The picked learner's photo URL from the same sessionStorage entry, or null when they have none.
export function getLearnerPhotoUrl(): string | null {
  try {
    const saved = sessionStorage.getItem("selectedLearner");
    return saved ? ((JSON.parse(saved) as { photoUrl?: string | null }).photoUrl ?? null) : null;
  } catch {
    return null;
  }
}

// 1 -> "1st", 2 -> "2nd", 3 -> "3rd", 4 -> "4th", 11 -> "11th", ...
export function ordinal(n: number): string {
  const v = n % 100;
  if (v >= 11 && v <= 13) return `${n}th`;
  switch (n % 10) {
    case 1:
      return `${n}st`;
    case 2:
      return `${n}nd`;
    case 3:
      return `${n}rd`;
    default:
      return `${n}th`;
  }
}

export function pickRandom<T>(list: T[]): T {
  return list[Math.floor(Math.random() * list.length)];
}
